package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

type codePointRange struct{ lo, hi rune }

func main() {
	out := flag.String("out", "emoji_tables.go", "the Go file to write")
	version := flag.String("version", unicode.Version, "the Unicode version of emoji-data.txt, matching Go's unicode tables")
	flag.Parse()
	url := fmt.Sprintf("https://www.unicode.org/Public/%s/ucd/emoji/emoji-data.txt", *version)
	data, err := download(url)
	if err != nil {
		log.Fatal(err)
	}
	properties, err := parseEmojiData(data, "Extended_Pictographic", "Emoji_Modifier")
	if err != nil {
		log.Fatal(err)
	}
	digest := sha256.Sum256(data)
	source, err := render(*version, url, hex.EncodeToString(digest[:]), properties)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, source, 0o644); err != nil {
		log.Fatal(err)
	}
}

func download(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func parseEmojiData(data []byte, wanted ...string) (map[string][]codePointRange, error) {
	properties := map[string][]codePointRange{}
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		property := strings.TrimSpace(fields[1])
		if !slices.Contains(wanted, property) {
			continue
		}
		lo, hi, err := parseRange(strings.TrimSpace(fields[0]))
		if err != nil {
			return nil, err
		}
		ranges := properties[property]
		if n := len(ranges); n > 0 && ranges[n-1].hi+1 == lo {
			ranges[n-1].hi = hi
		} else {
			ranges = append(ranges, codePointRange{lo, hi})
		}
		properties[property] = ranges
	}
	for _, property := range wanted {
		if len(properties[property]) == 0 {
			return nil, fmt.Errorf("emoji-data.txt names no %s code points", property)
		}
	}
	return properties, scanner.Err()
}

func parseRange(field string) (rune, rune, error) {
	first, last, isRange := strings.Cut(field, "..")
	lo, err := strconv.ParseUint(first, 16, 32)
	if err != nil {
		return 0, 0, err
	}
	if !isRange {
		return rune(lo), rune(lo), nil
	}
	hi, err := strconv.ParseUint(last, 16, 32)
	return rune(lo), rune(hi), err
}

func render(version, url, digest string, properties map[string][]codePointRange) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/emojigen; DO NOT EDIT.\n\npackage worker\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&b, "const (\n\temojiDataVersion = %q\n\temojiDataURL = %q\n\temojiDataSHA256 = %q\n)\n\n", version, url, digest)
	for _, table := range []struct{ name, property string }{
		{"extendedPictographic", "Extended_Pictographic"},
		{"emojiModifier", "Emoji_Modifier"},
	} {
		fmt.Fprintf(&b, "var %s = &unicode.RangeTable{\n", table.name)
		var r16, r32 []codePointRange
		for _, r := range properties[table.property] {
			switch {
			case r.hi <= 0xFFFF:
				r16 = append(r16, r)
			case r.lo > 0xFFFF:
				r32 = append(r32, r)
			default:
				r16 = append(r16, codePointRange{r.lo, 0xFFFF})
				r32 = append(r32, codePointRange{0x10000, r.hi})
			}
		}
		if len(r16) > 0 {
			b.WriteString("\tR16: []unicode.Range16{\n")
			for _, r := range r16 {
				fmt.Fprintf(&b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r.lo, r.hi)
			}
			b.WriteString("\t},\n")
		}
		if len(r32) > 0 {
			b.WriteString("\tR32: []unicode.Range32{\n")
			for _, r := range r32 {
				fmt.Fprintf(&b, "\t\t{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", r.lo, r.hi)
			}
			b.WriteString("\t},\n")
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}
